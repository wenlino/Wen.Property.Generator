using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;

namespace Wen.Property.Generator;

[Generator]
public sealed class WenPropertyGenerator : IIncrementalGenerator
{
    private const string AttributeFullName = "Wen.Property.Generator.WenGenerateAccessorsAttribute";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        // 1. 注入基础设施代码（Attribute、接口、零反射工厂、扩展方法）
        context.RegisterPostInitializationOutput(static ctx =>
        {
            ctx.AddSource("WenPropertyAttributes.g.cs", SourceText.From(AttributeSource, Encoding.UTF8));
            ctx.AddSource("WenPropertyInterfaces.g.cs", SourceText.From(InterfaceSource, Encoding.UTF8));
            ctx.AddSource("WenPropertyFactory.g.cs", SourceText.From(FactorySource, Encoding.UTF8));
            ctx.AddSource("WenPropertyExtensions.g.cs", SourceText.From(ExtensionsSource, Encoding.UTF8));
        });

        // 2. 增量管道：预过滤带 Attribute 的类声明，避免所有类都进入 transform
        var classDeclarations = context.SyntaxProvider.CreateSyntaxProvider(
            predicate: static (node, _) => node is ClassDeclarationSyntax c && c.AttributeLists.Count > 0,
            transform: static (ctx, _) => GetClassInfo(ctx))
            .Where(static m => m is not null)
            .Select(static (m, _) => m!.Value)
            .Collect();

        // 3. 注册输出
        context.RegisterSourceOutput(classDeclarations, static (spc, classInfos) =>
        {
            // 按完全限定名去重（处理 partial 类多次声明等情况）
            var seen = new HashSet<string>();
            foreach (var info in classInfos)
            {
                if (!seen.Add(info.FullyQualifiedType)) continue;
                GenerateAccessorCode(spc, info);
            }
        });
    }

    // 提取目标类信息，跳过泛型类与嵌套类
    private static ClassInfo? GetClassInfo(GeneratorSyntaxContext context)
    {
        var classDeclaration = (ClassDeclarationSyntax)context.Node;
        var symbol = context.SemanticModel.GetDeclaredSymbol(classDeclaration) as INamedTypeSymbol;
        if (symbol is null) return null;

        // 跳过泛型类定义与嵌套类，避免生成复杂场景出错
        if (symbol.IsGenericType) return null;
        if (symbol.ContainingType is not null) return null;

        // 完全限定名匹配 Attribute，避免误匹配同名特性
        bool hasAttribute = symbol.GetAttributes().Any(a =>
            a.AttributeClass is { } ac && ac.ToDisplayString() == AttributeFullName);
        if (!hasAttribute) return null;

        string name = symbol.Name;
        string ns = symbol.ContainingNamespace.IsGlobalNamespace
            ? string.Empty
            : symbol.ContainingNamespace.ToDisplayString();
        string fullyQualifiedType = symbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

        return new ClassInfo(name, ns, fullyQualifiedType, symbol);
    }

    // 生成聚合访问器代码 + ModuleInitializer 注册器（AOT 关键：零运行时反射）
    private static void GenerateAccessorCode(SourceProductionContext context, ClassInfo info)
    {
        // 收集所有有效属性：public、非静态、非索引器、非显式接口实现
        var properties = new List<IPropertySymbol>();
        foreach (var member in info.Symbol.GetMembers())
        {
            if (member is not IPropertySymbol prop) continue;
            if (prop.DeclaredAccessibility != Accessibility.Public) continue;
            if (prop.IsStatic) continue;
            if (prop.IsIndexer) continue;
            if (!prop.ExplicitInterfaceImplementations.IsDefaultOrEmpty) continue;
            properties.Add(prop);
        }

        var sb = new StringBuilder();
        string name = info.Name;
        string fqt = info.FullyQualifiedType;
        bool hasNamespace = !string.IsNullOrEmpty(info.Namespace);
        string indent = hasNamespace ? "    " : string.Empty;

        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("using System;");
        sb.AppendLine("using System.Collections.Generic;");
        sb.AppendLine();

        if (hasNamespace)
        {
            sb.AppendLine($"namespace {info.Namespace}");
            sb.AppendLine("{");
        }

        // 访问器类
        sb.AppendLine($"{indent}internal sealed class {name}_WenAccessors : global::Wen.Property.Generator.IWenPropertyAccessor<{fqt}>");
        sb.AppendLine($"{indent}{{");

        // _names 数组
        sb.AppendLine($"{indent}    private static readonly string[] _names = new[]");
        sb.AppendLine($"{indent}    {{");
        foreach (var p in properties)
        {
            sb.AppendLine($"{indent}        \"{p.Name}\",");
        }
        sb.AppendLine($"{indent}    }};");
        sb.AppendLine();

        // PropertyNames
        sb.AppendLine($"{indent}    public IReadOnlyList<string> PropertyNames => _names;");
        sb.AppendLine();

        // ContainsProperty
        sb.AppendLine($"{indent}    public bool ContainsProperty(string propertyName) => propertyName switch");
        sb.AppendLine($"{indent}    {{");
        foreach (var p in properties)
        {
            sb.AppendLine($"{indent}        \"{p.Name}\" => true,");
        }
        sb.AppendLine($"{indent}        _ => false");
        sb.AppendLine($"{indent}    }};");
        sb.AppendLine();

        // GetPropertyValue (object? 版本，值类型自动装箱)
        sb.AppendLine($"{indent}    public object? GetPropertyValue({fqt} item, string propertyName) => propertyName switch");
        sb.AppendLine($"{indent}    {{");
        foreach (var p in properties)
        {
            sb.AppendLine($"{indent}        \"{p.Name}\" => item.{p.Name},");
        }
        sb.AppendLine($"{indent}        _ => throw new ArgumentException($\"属性 '{{propertyName}}' 在类型 '{name}' 上不存在。\", nameof(propertyName))");
        sb.AppendLine($"{indent}    }};");
        sb.AppendLine();

        // SetPropertyValue (object? 版本)
        sb.AppendLine($"{indent}    public void SetPropertyValue({fqt} item, string propertyName, object? value)");
        sb.AppendLine($"{indent}    {{");
        sb.AppendLine($"{indent}        switch (propertyName)");
        sb.AppendLine($"{indent}        {{");
        foreach (var p in properties)
        {
            if (p.IsReadOnly)
            {
                sb.AppendLine($"{indent}            case \"{p.Name}\": throw new ArgumentException($\"属性 '{{propertyName}}' 是只读的，无法设置。\", nameof(propertyName));");
            }
            else
            {
                string ptype = p.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                sb.AppendLine($"{indent}            case \"{p.Name}\": item.{p.Name} = ({ptype})value!; break;");
            }
        }
        sb.AppendLine($"{indent}            default: throw new ArgumentException($\"属性 '{{propertyName}}' 不存在或只读。\", nameof(propertyName));");
        sb.AppendLine($"{indent}        }}");
        sb.AppendLine($"{indent}    }}");
        sb.AppendLine();

        // GetPropertyValue<TValue> (强类型泛型版，无装箱拆箱损耗)
        sb.AppendLine($"{indent}    public TValue GetPropertyValue<TValue>({fqt} item, string propertyName) => propertyName switch");
        sb.AppendLine($"{indent}    {{");
        foreach (var p in properties)
        {
            sb.AppendLine($"{indent}        \"{p.Name}\" => (TValue)(object)item.{p.Name}!,");
        }
        sb.AppendLine($"{indent}        _ => throw new ArgumentException($\"属性 '{{propertyName}}' 在类型 '{name}' 上不存在。\", nameof(propertyName))");
        sb.AppendLine($"{indent}    }};");
        sb.AppendLine();

        // SetPropertyValue<TValue> (强类型泛型版)
        sb.AppendLine($"{indent}    public void SetPropertyValue<TValue>({fqt} item, string propertyName, TValue value)");
        sb.AppendLine($"{indent}    {{");
        sb.AppendLine($"{indent}        switch (propertyName)");
        sb.AppendLine($"{indent}        {{");
        foreach (var p in properties)
        {
            if (p.IsReadOnly)
            {
                sb.AppendLine($"{indent}            case \"{p.Name}\": throw new ArgumentException($\"属性 '{{propertyName}}' 是只读的，无法设置。\", nameof(propertyName));");
            }
            else
            {
                string ptype = p.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                sb.AppendLine($"{indent}            case \"{p.Name}\": item.{p.Name} = ({ptype})(object)value!; break;");
            }
        }
        sb.AppendLine($"{indent}            default: throw new ArgumentException($\"属性 '{{propertyName}}' 不存在或只读。\", nameof(propertyName));");
        sb.AppendLine($"{indent}        }}");
        sb.AppendLine($"{indent}    }}");
        sb.AppendLine();

        // GetPropertyType
        sb.AppendLine($"{indent}    public Type GetPropertyType(string propertyName) => propertyName switch");
        sb.AppendLine($"{indent}    {{");
        foreach (var p in properties)
        {
            string ptype = p.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            sb.AppendLine($"{indent}        \"{p.Name}\" => typeof({ptype}),");
        }
        sb.AppendLine($"{indent}        _ => throw new ArgumentException($\"属性 '{{propertyName}}' 在类型 '{name}' 上不存在。\", nameof(propertyName))");
        sb.AppendLine($"{indent}    }};");
        sb.AppendLine($"{indent}}}");
        sb.AppendLine();

        // 编译期注册器（AOT 关键）：模块加载时注册，零运行时反射
        sb.AppendLine($"{indent}internal static class {name}_WenAccessorsInit");
        sb.AppendLine($"{indent}{{");
        sb.AppendLine($"{indent}    [System.Runtime.CompilerServices.ModuleInitializer]");
        sb.AppendLine($"{indent}    internal static void Init()");
        sb.AppendLine($"{indent}        => global::Wen.Property.Generator.WenPropertyAccessorFactory.Register(new {name}_WenAccessors());");
        sb.AppendLine($"{indent}}}");

        if (hasNamespace)
        {
            sb.AppendLine("}");
        }

        context.AddSource($"{name}_WenAccessors.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
    }

    // 普通结构体（netstandard2.0 无 IsExternalInit，不能用 record struct）
    private readonly struct ClassInfo
    {
        public readonly string Name;
        public readonly string Namespace;
        public readonly string FullyQualifiedType;
        public readonly INamedTypeSymbol Symbol;

        public ClassInfo(string name, string ns, string fullyQualifiedType, INamedTypeSymbol symbol)
        {
            Name = name;
            Namespace = ns;
            FullyQualifiedType = fullyQualifiedType;
            Symbol = symbol;
        }
    }

    private const string AttributeSource = @"// <auto-generated/>
#nullable enable
namespace Wen.Property.Generator
{
    [System.AttributeUsage(System.AttributeTargets.Class, Inherited = false)]
    public sealed class WenGenerateAccessorsAttribute : System.Attribute { }
}
";

    private const string InterfaceSource = @"// <auto-generated/>
#nullable enable
namespace Wen.Property.Generator
{
    public interface IWenPropertyAccessor<TItem> where TItem : class
    {
        object? GetPropertyValue(TItem item, string propertyName);
        void SetPropertyValue(TItem item, string propertyName, object? value);
        TValue GetPropertyValue<TValue>(TItem item, string propertyName);
        void SetPropertyValue<TValue>(TItem item, string propertyName, TValue value);
        System.Type GetPropertyType(string propertyName);
        bool ContainsProperty(string propertyName);
        System.Collections.Generic.IReadOnlyList<string> PropertyNames { get; }
    }
}
";

    private const string FactorySource = @"// <auto-generated/>
#nullable enable
namespace Wen.Property.Generator
{
    public static class WenPropertyAccessorFactory
    {
        public static global::Wen.Property.Generator.IWenPropertyAccessor<TItem> GetAccessor<TItem>()
            where TItem : class
        {
            return global::Wen.Property.Generator.WenPropertyAccessorCache<TItem>.Accessor
                ?? throw new System.InvalidOperationException(
                    $""未找到类型 {typeof(TItem).Name} 的属性访问器。请确认该类型已标注 [WenGenerateAccessors] 特性。"");
        }

        internal static void Register<TItem>(global::Wen.Property.Generator.IWenPropertyAccessor<TItem> accessor)
            where TItem : class
            => global::Wen.Property.Generator.WenPropertyAccessorCache<TItem>.Accessor = accessor;
    }

    internal static class WenPropertyAccessorCache<TItem> where TItem : class
    {
        internal static global::Wen.Property.Generator.IWenPropertyAccessor<TItem>? Accessor;
    }
}
";

    private const string ExtensionsSource = @"// <auto-generated/>
#nullable enable
namespace Wen.Property.Generator
{
    public static class WenPropertyExtensions
    {
        public static object? GetPropertyValue<TItem>(this TItem item, string propertyName) where TItem : class
            => global::Wen.Property.Generator.WenPropertyAccessorFactory.GetAccessor<TItem>().GetPropertyValue(item, propertyName);

        public static void SetPropertyValue<TItem>(this TItem item, string propertyName, object? value) where TItem : class
            => global::Wen.Property.Generator.WenPropertyAccessorFactory.GetAccessor<TItem>().SetPropertyValue(item, propertyName, value);

        public static TValue GetPropertyValue<TItem, TValue>(this TItem item, string propertyName) where TItem : class
            => global::Wen.Property.Generator.WenPropertyAccessorFactory.GetAccessor<TItem>().GetPropertyValue<TValue>(item, propertyName);

        public static void SetPropertyValue<TItem, TValue>(this TItem item, string propertyName, TValue value) where TItem : class
            => global::Wen.Property.Generator.WenPropertyAccessorFactory.GetAccessor<TItem>().SetPropertyValue<TValue>(item, propertyName, value);

        public static bool ContainsProperty<TItem>(this TItem item, string propertyName) where TItem : class
            => global::Wen.Property.Generator.WenPropertyAccessorFactory.GetAccessor<TItem>().ContainsProperty(propertyName);

        public static System.Type GetPropertyType<TItem>(this TItem item, string propertyName) where TItem : class
            => global::Wen.Property.Generator.WenPropertyAccessorFactory.GetAccessor<TItem>().GetPropertyType(propertyName);

        public static System.Collections.Generic.IReadOnlyList<string> GetPropertyNames<TItem>(this TItem item) where TItem : class
            => global::Wen.Property.Generator.WenPropertyAccessorFactory.GetAccessor<TItem>().PropertyNames;
    }
}
";
}
